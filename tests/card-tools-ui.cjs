require('../desktop/process-stdio.cjs').installStdioGuards();
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'card-tools-ui-'));
const output = path.join(root, 'artifacts/card-tools-ui'); fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(directory, 'profile'));
app.on('window-all-closed', () => {});
const report = { checks: [], errors: [], downloads: [] };
let runtime, win;
const js = source => win.webContents.executeJavaScript(source, true);
const frame = source => js(`(async()=>{const w=document.querySelector('#card-studio-frame').contentWindow,d=w.document;${source}})()`);
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
async function wait(label, test) { const end = Date.now() + 25000; while (Date.now() < end) { if (await test()) return; await pause(100); } throw new Error('等待超时：' + label); }
async function shot(name) { await pause(200); fs.writeFileSync(path.join(output, name), (await win.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG()); }
const deadline = setTimeout(() => { report.errors.push('桌面验收超时'); fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(report)); app.exit(1); }, 120000);
app.whenReady().then(async () => {
  const { createWorkbench } = await import(pathToFileURL(path.join(root, 'framework/server.mjs')));
  const { getPngChara } = await import(pathToFileURL(path.join(root, 'integrations/xiaoxi/tools/card.mjs')));
  runtime = await createWorkbench({ dataDir: path.join(directory, 'data') });
  const api = async (route, data) => { const response = await fetch(runtime.url + route, { method: data === undefined ? 'GET' : 'POST', ...(data === undefined ? {} : { headers: { 'content-type': 'application/json' }, body: JSON.stringify(data) }) }); const value = await response.json(); assert.ok(response.ok, JSON.stringify(value)); return value; };
  await api('/api/instances/migrate-legacy', {});
  await api('/api/modules/cards/enable', {});
  const instance = (await api('/api/instances', { moduleId: 'cards', name: '导出验收' })).instance;
  const prefix = '/instances/' + instance.id;
  await api(prefix + '/api/modules/cards/studio', {});
  await api(prefix + '/card-studio/api/new', { name: '星禾导出验收' });
  win = new BrowserWindow({ show: false, width: 1500, height: 1050, webPreferences: { offscreen: true, contextIsolation: true, sandbox: true } });
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) report.errors.push(message); });
  win.webContents.session.on('will-download', (_event, item) => { item.setSavePath(path.join(output, item.getFilename())); item.once('done', (_event, state) => report.downloads.push({ name: item.getFilename(), state })); });
  await win.loadURL(runtime.url + '/#/module/cards');
  await wait('作品列表', () => js("!!document.querySelector('[data-edit-card]')"));
  await js("document.querySelector('[data-edit-card]').click()");
  await js("document.querySelector('[data-tour-skip]')?.click()");
  await wait('编辑器', () => frame("return w.__workbenchReady?.() && !!d.querySelector('#btn-export-card');").catch(() => false));
  assert.equal(await frame("return d.querySelector('#workspace-drawer').hidden;"), true);
  assert.equal(await frame("return d.querySelector('#btn-export-card').getBoundingClientRect().width>0;"), true);
  await frame("d.querySelector('#btn-export-card').focus();d.querySelector('#btn-export-card').click();");
  await wait('空卡错误', () => frame("return !!d.querySelector('#artifact-error');"));
  assert.match(await frame("return d.querySelector('#artifact-error').textContent;"), /description|描述/);
  await shot('empty-card-error.png');
  await frame("d.querySelector('#artifact-error button').click();");
  report.checks.push('工作区抽屉关闭时常驻导出按钮可见；空卡显示具体失败原因');
  for (const [key, content] of [['description', '成年天文学研究员星禾。'], ['first_mes', '今晚一起观星吧，{{user}}。']]) await api(prefix + '/card-studio/api/save/' + encodeURIComponent('星禾导出验收'), { kind: 'text', key, content });
  await frame("const input=d.querySelector('#chat-input');input.value='尚未发送的草稿';input.dispatchEvent(new w.Event('input',{bubbles:true}));d.querySelector('#btn-export-card').focus();d.querySelector('#btn-export-card').click();");
  await wait('成品窗口', () => frame("return !!d.querySelector('#artifact-dialog');"));
  await shot('export-files.png');
  for (const label of ['下载 JSON', '下载 PNG']) await frame(`Array.from(d.querySelectorAll('#artifact-dialog button')).find(button=>button.textContent===${JSON.stringify(label)}).click();`);
  await wait('两个文件下载', () => report.downloads.length === 2);
  assert.ok(report.downloads.every(item => item.state === 'completed'));
  const json = JSON.parse(fs.readFileSync(path.join(output, '星禾导出验收.json'), 'utf8'));
  assert.deepEqual(getPngChara(fs.readFileSync(path.join(output, '星禾导出验收.png'))), json);
  assert.equal(json.data.description, '成年天文学研究员星禾。');
  await frame("Array.from(d.querySelectorAll('#artifact-dialog button')).find(button=>button.textContent==='关闭').click();");
  assert.equal(await frame("return d.activeElement.id;"), 'btn-export-card');
  assert.equal(await frame("return d.querySelector('#chat-input').value;"), '尚未发送的草稿');
  await frame("d.querySelector('#btn-view-card-artifacts').focus();d.querySelector('#btn-view-card-artifacts').click();");
  await wait('查看既有成品', () => frame("return !!d.querySelector('#artifact-dialog');"));
  report.checks.push('实例内真实导出并下载 PNG/JSON，内容一致；关闭后焦点返回且聊天草稿保留；常驻查看成品可用');
  report.ok = report.errors.length === 0;
}).catch(async error => { report.ok = false; report.errors.push(error.stack || error.message); if (win) await shot('failure.png').catch(() => {}); }).finally(async () => {
  clearTimeout(deadline); win?.destroy(); await runtime?.close();
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(report, null, 2), 'utf8');
  // Electron 仍持有当前 userData 的系统锁；退出后由调用方按报告路径清理。
  assert.ok(path.resolve(directory).startsWith(path.resolve(os.tmpdir()) + path.sep));
  report.temporaryDirectory = directory;
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(report, null, 2), 'utf8');
  console.log(JSON.stringify(report)); app.exit(report.ok ? 0 : 1);
});
