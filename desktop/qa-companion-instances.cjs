require('./process-stdio.cjs').installStdioGuards();
const electron=require('electron');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {pathToFileURL}=require('node:url');
const {CompanionHost}=require('./companion-host.cjs');
const {WorkbenchImmersion}=require('./workbench-immersion.cjs');
const output=fs.mkdtempSync(path.join(os.tmpdir(),'ai-future-native-instances-'));
electron.app.setPath('userData',path.join(output,'profile'));
const report={output,checks:[],errors:[]};
const hosts=[];
const write=()=>fs.writeFileSync(path.join(output,'result.json'),JSON.stringify(report,null,2),'utf8');
console.log('QA_OUTPUT='+output);
process.on('uncaughtException',error=>{report.errors.push(error.stack);write();});
let root,immersion;
const deadline=setTimeout(()=>{report.errors.push('原生多实例检查超过三分钟');write();electron.app.exit(1);},180000);
const key=(contents,name)=>{let prevented=false;contents.emit('before-input-event',{preventDefault(){prevented=true;}},{type:'keyDown',key:name});return prevented;};
electron.app.whenReady().then(async()=>{
  const {inspectAiriInstall}=await import(pathToFileURL(path.join(__dirname,'../framework/companion-source.mjs')).href);
  const install=inspectAiriInstall();assert.equal(install.available,true,install.reason);
  root=new electron.BrowserWindow({show:false,width:1200,height:900,webPreferences:{offscreen:true,contextIsolation:true,sandbox:true}});
  await root.loadURL('data:text/html,<html><body>Isolated native instances</body></html>#/module/companion');
  immersion=new WorkbenchImmersion({getWindow:()=>root,ipcMain:electron.ipcMain});immersion.attach(root.webContents);
  const create=id=>{
    const host=new CompanionHost({instanceId:id,getWindow:()=>root,qa:true,onError:error=>report.errors.push(String(error)),onContents:(contents,view)=>{
      immersion.attach(contents,{moduleId:'companion',isEligibleSource:()=>!host.disposed&&view.embedded&&host.activeWindow===view&&host.area.visible});
      contents.session.webRequest.onBeforeRequest({urls:['http://*/*','https://*/*','ws://*/*','wss://*/*']},(details,callback)=>{
        const url=new URL(details.url);callback({cancel:!['127.0.0.1','localhost'].includes(url.hostname)});
      });
    }});hosts.push(host);return host;
  };
  const start=host=>host.start({install,dataDir:path.join(output,host.instanceId),bootstrap:{baseUrl:'http://127.0.0.1:1/internal/companion/ai/v1',token:'qa-'+host.instanceId,model:'disabled',theme:'light',character:null}});
  const a=create('a'),b=create('b');
  await Promise.all([start(a),start(b)]);
  assert.notEqual(a.hostId,b.hostId);assert.notEqual(a.bridge,b.bridge);assert.notEqual(a.serverChannelPort,b.serverChannelPort);assert.notEqual(a.session,b.session);
  const stage=host=>[...host.windows.values()].find(window=>window.kind==='stage').webContents;
  const state=contents=>contents.executeJavaScript('({marker:localStorage.getItem("qa-instance"),channel:localStorage.getItem("settings/connection/websocket-url"),provider:JSON.parse(localStorage.getItem("settings/providers/configured"))["workbench-shared"].config.apiKey})');
  const sa=stage(a),sb=stage(b);
  a.ipcScope.api.handle('qa-instance',()=>a.instanceId);b.ipcScope.api.handle('qa-instance',()=>b.instanceId);
  const invoke=contents=>contents.executeJavaScript('window.electron.ipcRenderer.invoke("qa-instance")');
  assert.equal(await invoke(sa),'a');assert.equal(await invoke(sb),'b');
  await sa.executeJavaScript('localStorage.setItem("qa-instance","A");void 0');
  await sb.executeJavaScript('localStorage.setItem("qa-instance","B");void 0');
  assert.deepEqual(await state(sa),{marker:'A',channel:`ws://127.0.0.1:${a.serverChannelPort}/ws`,provider:'qa-a'});
  assert.deepEqual(await state(sb),{marker:'B',channel:`ws://127.0.0.1:${b.serverChannelPort}/ws`,provider:'qa-b'});
  report.checks.push('两个 AIRI 原生舞台并行启动，独立 ESM 容器、session、通道端口、bootstrap 和 localStorage');
  a.viewport({visible:true,x:0,y:0,width:900,height:700});b.viewport({visible:false});
  assert.equal(key(sb,'F11'),false);assert.equal(key(sa,'F11'),true);await new Promise(resolve=>setImmediate(resolve));
  assert.equal(immersion.state().active,true);assert.equal(key(sb,'Escape'),false);assert.equal(key(sa,'Escape'),true);await new Promise(resolve=>setImmediate(resolve));
  a.viewport({visible:false});b.viewport({visible:true,x:0,y:0,width:900,height:700});
  assert.equal(key(sa,'F11'),false);assert.equal(key(sb,'F11'),true);await new Promise(resolve=>setImmediate(resolve));
  assert.equal(key(sb,'Escape'),true);await new Promise(resolve=>setImmediate(resolve));
  report.checks.push('F11/Esc 只接受当前可见原生实例');
  const signalB=b.processScope.api.listeners('SIGINT');assert.ok(signalB.length);
  await a.close();assert.equal(sa.isDestroyed(),true);assert.equal(sb.isDestroyed(),false);assert.ok(b.processScope.api.listeners('SIGINT').length);
  assert.equal(await invoke(sb),'b');
  await b.open('settings','/settings');assert.equal(b.activeWindow.kind,'settings');
  await b.open('stage');assert.equal((await state(sb)).marker,'B');
  report.checks.push('停止 A 后 B 的原生设置 IPC、舞台与进程监听保持可用');
  const reopened=create('a');await start(reopened);
  reopened.ipcScope.api.handle('qa-instance',()=>reopened.instanceId);assert.equal(await invoke(stage(reopened)),'a');assert.equal(await invoke(sb),'b');
  assert.notEqual(reopened.hostId,a.hostId);assert.notEqual(reopened.bridge,a.bridge);assert.equal((await state(stage(reopened))).marker,'A');
  assert.equal((await state(sb)).marker,'B');report.checks.push('同一实例 ID 使用新宿主重开，保留自身浏览器资料且不影响 B');
  await reopened.close();await b.close();report.ok=report.errors.length===0;write();console.log(JSON.stringify(report));
}).catch(error=>{report.ok=false;report.errors.push(error.stack);write();console.error(error);}).finally(async()=>{
  clearTimeout(deadline);for(const host of hosts)await host.close().catch(error=>{report.errors.push(String(error));report.ok=false;});
  immersion?.close();if(root&&!root.isDestroyed())root.destroy();write();electron.app.exit(report.ok?0:1);
});
