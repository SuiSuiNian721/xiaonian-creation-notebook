// 扫描文本，返回所有八股命中
export function scanBagua(text) {
  const hits = [];
  if (!text || typeof text !== 'string') return hits;
  for (const rule of BAGUA_RULES) {
    rule.re.lastIndex = 0; // 全局正则复用时必须复位
    let m;
    while ((m = rule.re.exec(text)) !== null) {
      hits.push({ type: rule.type, word: m[0], note: rule.note, index: m.index });
      if (m.index === rule.re.lastIndex) rule.re.lastIndex++; // 防零宽匹配死循环
    }
  }
  return hits;
}

// 按 type 汇总命中，便于诊断层展示：{ 万能美人: ['倾国倾城', ...], ... }
export function summarizeBagua(text) {
  const byType = {};
  for (const h of scanBagua(text)) {
    if (!byType[h.type]) byType[h.type] = { words: [], note: h.note };
    if (!byType[h.type].words.includes(h.word)) byType[h.type].words.push(h.word);
  }
  return byType;
}
